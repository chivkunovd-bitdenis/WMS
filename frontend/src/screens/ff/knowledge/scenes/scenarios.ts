import type { SceneId } from './registry'

/**
 * Сценарии для проигрывателя базы знаний.
 *
 * Сценарий — это тот же порядок действий, что и в тексте статьи, только
 * разыгранный на живом макете: рамка встаёт на нужную кнопку, под ней
 * появляется подпись, потом кнопка нажимается по-настоящему и приходит
 * очередь следующего шага. Смысл в том, что читать «нажмите Наполнить»
 * и увидеть, куда именно на экране это «Наполнить» приезжает, — две разные
 * степени понятности, особенно для нового сотрудника.
 *
 * Якорь шага (`anchor`) — обычный CSS-селектор внутри макета. Почти везде в
 * портале проставлены `data-testid`, их и используем: они не меняются от
 * перевёрстки, в отличие от текста и позиции.
 */

export type ScenarioStep = {
  /** Какой макет показывать. Соседние шаги в одном макете идут без перезагрузки. */
  scene: SceneId
  /** CSS-селектор элемента, на который встаёт рамка. */
  anchor: string
  title: string
  text: string
  /**
   * Нажимать ли элемент по-настоящему в конце шага. Выключаем там, где нажатие
   * ничего не меняет (пункт меню в макете) или увело бы макет не туда.
   */
  click?: boolean
  /** Сколько держать шаг перед нажатием, мс. Длинные подписи — дольше. */
  dwellMs?: number
}

export type Scenario = {
  id: string
  title: string
  steps: ScenarioStep[]
}

