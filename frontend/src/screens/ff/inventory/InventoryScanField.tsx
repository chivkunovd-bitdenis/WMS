import { ScannerField } from '../../../ui-kit'
import { useBarcodeScanner } from '../../../hooks/useBarcodeScanner'

/**
 * Поле сканера на пересчёте.
 *
 * ⛔ Скан НЕ ЗАВИСИТ от того, стоит ли курсор в поле.
 *
 * Так сделано не для красоты. Приёмка и отгрузка слушают клавиатуру целиком —
 * и у них сканер работает годами. Инвентаризация одна была построена иначе:
 * «символы обязаны попасть в текстовое поле, и поле обязано быть в фокусе».
 * Любая мелочь, отбирающая фокус — нажатая кнопка, перерисовка документа на
 * пятьсот строк, случайный клик мимо, — и штрихкод уходил в пустоту. Оператор
 * при этом видел ровно то, что описывал: «пикаю, а система не реагирует».
 *
 * Теперь код ловится на уровне документа: сканер набирает символы, заканчивает
 * их своим Enter, и пачка приезжает сюда, где бы ни стоял курсор. Поле осталось
 * — в него можно вбить код руками и видно, что пришло, — но роль у него теперь
 * вспомогательная, а не несущая.
 *
 * Значение поля живёт в DOM, а не в состоянии React: управляемое поле на
 * тяжёлом документе теряло символы (родитель перерисовывается раньше ребёнка,
 * и на коммите поле получало старое значение — оператор видел «46» вместо
 * полного штрихкода).
 */
export function InventoryScanField({
  expects,
  error,
  notice,
  onScan,
  /** Пересчёт закрыт — слушать сканер незачем. */
  enabled = true,
  testId,
}: {
  expects: string
  error?: string | null
  notice?: string | null
  onScan: (code: string) => void
  enabled?: boolean
  testId: string
}) {
  useBarcodeScanner({ onScan, enabled })

  return (
    <ScannerField
      onScan={onScan}
      expects={expects}
      error={error ?? null}
      notice={notice ?? null}
      testId={testId}
    />
  )
}
