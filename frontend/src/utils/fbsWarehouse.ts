// I10 (21.08.2026): у большинства клиентов физически одна площадка (фулфилмент), но в
// таблице warehouses строк несколько — «основной» плюс склад-подстановка, который WMS сама
// создаёт под каждый склад WB при первой синхронизации заказов (см.
// `AUTO_FBS_WAREHOUSE_CODE_PREFIX` / `is_auto_fbs_wms_warehouse` в
// backend/app/services/fbs_warehouse_binding_service.py). Такой склад — это просто точка
// привязки на время, пока оператор не назначил настоящий склад; физически на нём ничего не
// лежит. Раньше он попадал в общий список наравне с настоящими складами: приёмка и создание
// заявок по умолчанию брали первый склад по алфавиту, а «FBS WB …» на латинице сортируется
// раньше кириллического «Основной» — именно так поставка 20.08 приехала не в ту ячейку.
//
// Эта функция — единственное место, которое знает признак склада-подстановки на фронте;
// используйте её везде, где считается, сколько складов реально можно выбрать, и куда
// подставлять склад по умолчанию.
export function isAutoFbsWarehouse(warehouse: { name: string; code: string }): boolean {
  return warehouse.code.startsWith('fbs-wb-') || warehouse.name.startsWith('FBS WB ')
}

// Склады, которые оператор может осмысленно выбрать как место хранения. Список
// складов-подстановок не считается «выбором» — I10: «один склад — ноль вопросов» должно
// работать и когда в базе есть служебные автосозданные записи.
export function realWarehouses<T extends { name: string; code: string }>(list: T[]): T[] {
  return list.filter((warehouse) => !isAutoFbsWarehouse(warehouse))
}

// Склад по умолчанию: первый настоящий склад, а не первый по алфавиту среди всех строк.
// Если настоящих складов почему-то нет (только служебные подстановки), не ломаем прежнее
// поведение — откатываемся на первый склад из полного списка.
export function primaryWarehouseId<T extends { id: string; name: string; code: string }>(
  list: T[],
): string | null {
  const real = realWarehouses(list)
  if (real.length > 0) {
    return real[0]!.id
  }
  return list[0]?.id ?? null
}
