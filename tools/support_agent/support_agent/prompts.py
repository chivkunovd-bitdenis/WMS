def owner_command_prompt(text: str, awaiting: list[dict[str, str]], target: int | None) -> str:
    lines = "\n".join(f"- {t['id']}: клиент {t['client']} ({t['kind']})" for t in awaiting) or "(нет)"
    return (
        "Владелец склада ответил в канале сводок. Определи, какое решение он принял.\n"
        f"Ожидают решения:\n{lines}\n"
        f"Он ответил на сообщение по обращению: {target if target else 'не указано'}\n"
        f"Его слова: {wrap(text)}\n\n"
        'Верни {"intent": "go|reject|postpone|mockup_yes|mockup_no|unclear|other", '
        '"ticket_ids": [номера], "all": true|false}. go — «кати», «делай», «делай хотфикс», '
        "«выкатывай»; reject — «не надо», «не делай»; postpone — «позже», «отложи»; mockup_yes/no — "
        "ответ про макет; unclear — похоже на решение, но непонятно какое или к чему; other — "
        "не про решения. all=true, если сказано «всё»/«все». Не выдумывай номера. " + JSON_ONLY
    )


