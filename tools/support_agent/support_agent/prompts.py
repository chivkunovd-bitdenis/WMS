def wrap(data: str) -> str:
    return f"<<<ДАННЫЕ\n{data}\nДАННЫЕ>>>"


def filter_prompt(message: str, open_tickets: list[dict[str, str]], waiting: list[int]) -> str:
    tickets = (
        "\n\n".join(wrap(f"- обращение {t['id']}: {t['title']}\n"
                         f"Полная переписка обращения:\n{t.get('messages', '')}")
                    for t in open_tickets) or "(нет)"
    )
    return (
        f"{DATA_NOTE}\n\nНовое сообщение из клиентского чата:\n{wrap(message)}\n\n"
        f"Открытые обращения этого чата:\n{tickets}\n"
        f"Обращения, ожидающие ответа клиента: {waiting or 'нет'}\n\n"
        "Сопоставь новое сообщение с полной перепиской открытых обращений, а не только с заголовком. "
        "Нумерованное дополнение (например, «2. Нужно…»), пояснение другого участника после голосового "
        "или ответ про уже обсуждаемый процесс отнеси к тому же обращению, если связь видна из содержания. "
        "Нумерация, один чат или близость по времени сами по себе не доказывают связь: самостоятельная "
        "новая просьба получает ticket_id=null. Не теряй отдельные пункты одного обращения. "
        'Верни {"relevant": true|false|"unsure", "ticket_id": <номер открытого обращения, к '
        'которому относится сообщение (в том числе как ответ на вопрос), или null>}. '
        f"Болтовня, приветствия, благодарности без просьбы — relevant=false. {JSON_ONLY}"
    )


def classify_prompt(text: str, form_type: str | None) -> str:
    hint = (
        f"Автор формы отметил тип: {'ошибка' if form_type == 'bug' else 'улучшение'}. Это только "
        "стартовое мнение, проверь по сути.\n"
        if form_type
        else ""
    )
    return (
        f"{DATA_NOTE}\n{hint}\nОбращение клиента склада:\n{wrap(text)}\n\n"
        'Классифицируй. Верни {"category": "bug|improvement|info|chatter|other", '
        '"confidence": "high|low", "title": "<5-10 слов по-человечески>"}. '
        "bug — что-то не работает или работает неверно; improvement — просьба сделать удобнее "
        "или добавить; info — просьба дать данные, выгрузку, пояснение (не поломка); chatter — "
        "болтовня; other — не уверен. Если сомневаешься — confidence=low. " + JSON_ONLY
    )


