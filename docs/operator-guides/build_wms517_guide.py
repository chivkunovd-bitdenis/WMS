def table(headers, rows, widths):
 t=D.add_table(rows=1, cols=len(headers));t.style='Table Grid';t.autofit=False
 for i,tx in enumerate(headers):
  t.rows[0].cells[i].text=tx
  t.columns[i].width=Cm(widths[i])
 for vals in rows:
  cells=t.add_row().cells
  for c,tx in zip(cells,vals): c.text=tx
 for row in t.rows:
  for i,c in enumerate(row.cells):
   c.width=Cm(widths[i])
   for para in c.paragraphs:
    para.paragraph_format.space_after=Pt(4);para.paragraph_format.space_before=Pt(4)
    for run in para.runs: run.font.size=Pt(10)
  pr=row._tr.get_or_add_trPr();pr.append(OxmlElement('w:cantSplit'))
