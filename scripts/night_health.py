#!/usr/bin/env python3
"""Механическая проверка здоровья ночи. Без единого вызова модели.

Смысл: дорогого сторожа будим не по таймеру, а по симптому. Таймер сам по себе ничего
не знает и, срабатывая каждые двадцать минут вхолостую, сжигает лимит ровно так же, как
это делал watchdog Codex — он тикал десять часов и не починил ничего.

Здесь наоборот: раз в несколько минут дёшево смотрим факты — время последней записи в
журнал, живой ли процесс, отвечают ли стенды, сколько карточек встало. Всё спокойно —
молчим и ничего не стоим. Появился симптом — печатаем его и выходим с кодом 1,
и только тогда просыпается агент.

    python3 scripts/night_health.py night/2026-08-22
"""
from __future__ import annotations

import json
import subprocess
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ТАЙМАУТ_ШАГА = 20 * 60          # столько же, сколько даёт шагу оркестратор
ПОЛОС = 6


def жив_оркестратор() -> bool:
    # Любая фаза, а не только «ночь»: проверка, ищущая одно слово, всю ночь будила
    # сторожа на живом оркестраторе — и каждое такое пробуждение стоит дорогой модели.
    р = subprocess.run(["pgrep", "-f", "night.py"], capture_output=True, text=True)
    return bool(р.stdout.strip())


def стенд_отвечает(полоса: int) -> bool:
    порт = f"3008{полоса}"
    р = subprocess.run(["curl", "-sf", "-m", "3", f"http://localhost:{порт}/health"],
                       capture_output=True)
    return р.returncode == 0


def main() -> int:
    if len(sys.argv) < 2:
        print("нужен путь к волне", file=sys.stderr)
        return 2
    волна = Path(sys.argv[1]).resolve()
    карточки = волна / "cards"
    if not карточки.exists():
        print(f"СИМПТОМ: нет папки карточек {карточки}")
        return 1

    симптомы: list[str] = []
    факты: dict = {}

    все = sorted(п for п in карточки.iterdir() if п.is_dir())
    отложено = [п.name for п in все if (п / "OTLOZHENO.md").exists()]
    факты["карточек"] = len(все)
    факты["отложено"] = len(отложено)

    # 1. Журнал давно не растёт, а оркестратор считает, что работает.
    журнал = волна / "JOURNAL.md"
    если_молчит = time.time() - журнал.stat().st_mtime if журнал.exists() else 0
    факты["молчит_минут"] = round(если_молчит / 60, 1)
    жив = жив_оркестратор()
    факты["оркестратор_жив"] = жив
    if жив and если_молчит > ТАЙМАУТ_ШАГА * 1.5:
        симптомы.append(
            f"оркестратор жив, но журнал молчит {факты['молчит_минут']} минут "
            f"при таймауте шага {ТАЙМАУТ_ШАГА // 60}")

    # 2. Оркестратор умер, а работа не доделана — очередь просто брошена.
    if not жив and len(отложено) < len(все) and любая_недоделана(все):
        симптомы.append("оркестратора нет в процессах, но карточки не доведены до конца")

    # 3. Стенды. Кликер без стенда бесполезен, и это чинится в одну команду.
    мёртвые = [п for п in range(1, ПОЛОС + 1) if not стенд_отвечает(п)]
    факты["стенды_мертвы"] = мёртвые
    if мёртвые and любая_дошла_до_кликера(все):
        симптомы.append(f"карточки дошли до браузера, а стенды полос {мёртвые} не отвечают")

    # 4. Массовая остановка по одной и той же причине — почти всегда внешняя,
    #    и почти всегда развязывается одним действием.
    причины: dict[str, int] = {}
    for п in все:
        ф = п / "OTLOZHENO.md"
        if ф.exists():
            первая = ф.read_text(encoding="utf-8", errors="replace").strip().splitlines()
            ключ = (первая[0] if первая else "?")[:80]
            причины[ключ] = причины.get(ключ, 0) + 1
    факты["причины"] = причины
    for ключ, n in причины.items():
        if n >= 3:
            симптомы.append(f"{n} карточек легли с одной причиной: {ключ}")

    print(json.dumps(факты, ensure_ascii=False, indent=2))
    if симптомы:
        print("\nСИМПТОМЫ:")
        for с in симптомы:
            print(f"  - {с}")
        return 1
    print("\nвсё спокойно")
    return 0


def любая_недоделана(все: list[Path]) -> bool:
    return any(not (п / "OTLOZHENO.md").exists() and not (п / "JUDGE.md").exists() for п in все)


def любая_дошла_до_кликера(все: list[Path]) -> bool:
    return any((п / "DEV.md").exists() and not (п / "JUDGE.md").exists() for п in все)


if __name__ == "__main__":
    sys.exit(main())
