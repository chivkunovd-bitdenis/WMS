#!/usr/bin/env python3
"""Механическая вычёска кандидатов в блокировки по экранам.

Полнота важнее ума: скрипт не решает, блокировка перед ним или мелочь — он тащит всё,
что похоже, и отдаёт агенту. Агент найдёт то, что заметит; скрипт находит всё.

Именно так ловится класс ошибок вроде «кнопка создания задания видна только в статусе
draft» — правила, которого нет ни в одном требовании, оно просто чьё-то предположение
в условии показа, и стоило оно полдня и десяти зависших поставок.

    python3 scripts/blockers/harvest.py                 # разложить по карточкам волны
    python3 scripts/blockers/harvest.py --посчитать     # только цифры, ничего не писать
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]

# Что тащим. Каждый образец — с объяснением, зачем он здесь, чтобы список можно было
# осмысленно править, а не гадать.
ОБРАЗЦЫ_ФРОНТ = [
    ("запрет-кнопки",   r"disabled=\{[^}]{0,160}\}",
     "кнопка или поле выключены условием"),
    ("скрытие-в-null",  r"\?[^:\n]{1,80}:\s*null",
     "элемент не показан по условию — самая незаметная блокировка"),
    ("проверка-статуса", r"\b\w*[Ss]tatus\b\s*(?:===|!==)\s*['\"][a-z_]+['\"]",
     "решение принимается по статусу предметной области"),
    ("ранний-выход",    r"if\s*\([^)]{1,80}\)\s*return\s+null",
     "экран или блок не рисуется вовсе"),
]
ОБРАЗЦЫ_БЭК = [
    ("доменный-отказ",  r"raise\s+[A-Z]\w*Error\([^)]{0,120}",
     "сервер отказывает с доменной причиной"),
    ("код-отказа",      r"code=['\"][a-z_]{4,40}['\"]",
     "типизированный код отказа, который увидит экран"),
]

ШУМ = re.compile(
    r"loading|isLoading|pending|busy|saving|submitting|!value|length\s*===\s*0|"
    r"disabled=\{true\}|disabled=\{false\}|isFetching",
    re.I,
)


def экраны() -> list[dict]:
    d = json.loads((КОРЕНЬ / "frontend/screens.registry.json").read_text(encoding="utf-8"))
    s = d if isinstance(d, list) else d.get("screens", d)
    return list(s.values()) if isinstance(s, dict) else s


ОКНО = 12   # строк вокруг находки: столько, чтобы понять условие, и не больше


def вычесать(путь: Path, образцы: list[tuple[str, str, str]]) -> list[tuple[str, int, str, str]]:
    try:
        строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return []
    найдено = []
    for н, строка in enumerate(строки, 1):
        for вид, образец, _ in образцы:
            if re.search(образец, строка):
                # Шум отсеиваем здесь, чтобы агент не тратил внимание на «disabled пока грузится».
                if ШУМ.search(строка):
                    continue
                # Кладём не ссылку, а кусок кода: агент, которому дали ссылку,
                # идёт открывать файл целиком — и один экран стоит пяти миллионов токенов.
                а, б = max(0, н - 1 - ОКНО), min(len(строки), н + ОКНО)
                кусок = "\n".join(
                    f"{'>' if i + 1 == н else ' '} {i + 1:5} {строки[i]}"[:220]
                    for i in range(а, б)
                )
                найдено.append((вид, н, кусок, путь.name))
                break
    return найдено


def ключи_экрана(э: dict) -> set[str]:
    """Слова, по которым серверный файл считается относящимся к экрану.

    В этом проекте бэкенд назван по доменам (fbs_supply_service, honest_sign_service),
    а маршрут экрана несёт тот же домен. Поэтому совпадения по слову хватает,
    и агенту не приходится грепать общую кучу из 1183 отказов.
    """
    слова = set()
    for кусок in re.split(r"[/_.-]", (э.get("route") or "") + "/" + (э.get("component") or "")):
        к = кусок.strip().lower()
        if len(к) > 2 and к not in {"app", "src", "screen", "page", "tsx", "ff"}:
            слова.add(к)
    for отн in list(э.get("files") or []) + list((э.get("shared") or {}).keys()):
        for кусок in re.split(r"[/_.-]", отн.lower()):
            if len(кусок) > 3 and кусок not in {"screens", "components", "utils", "hooks", "src"}:
                слова.add(кусок)
    return слова


def бэкендные_файлы() -> list[Path]:
    корень = КОРЕНЬ / "backend/app"
    return sorted(корень.rglob("*.py")) if корень.exists() else []


def main() -> int:
    только_счёт = "--посчитать" in sys.argv
    волна = КОРЕНЬ / "night" / "blockers" / "cards"
    итого = 0
    пусто = []

    бэк = {}
    for ф in бэкендные_файлы():
        н = вычесать(ф, ОБРАЗЦЫ_БЭК)
        if н:
            бэк[ф.relative_to(КОРЕНЬ)] = н

    for э in экраны():
        ид = э.get("id")
        if not ид:
            continue
        строки = []
        # У экрана два поля с файлами: свои (files) и общие с соседями (shared).
        # Блокировка в общем файле — самая опасная: она бьёт по нескольким экранам сразу,
        # и правка «под свой экран» ломает чужой.
        отн_файлы = list(э.get("files") or []) + sorted((э.get("shared") or {}).keys())
        for отн in отн_файлы:
            п = КОРЕНЬ / "frontend" / отн
            for вид, н, текст, _ in вычесать(п, ОБРАЗЦЫ_ФРОНТ):
                общий = отн in (э.get("shared") or {})
                метка = f" · ОБЩИЙ с {', '.join(x for x in (э.get('shared') or {})[отн] if x != ид)}" if общий else ""
                строки.append(f"- `{вид}`{метка} · `frontend/{отн}:{н}`\n  ```\n  {текст}\n  ```")
        итого += len(строки)
        if not строки:
            пусто.append(ид)
        if только_счёт:
            print(f"  {ид:6} {len(строки):4}")
            continue

        папка = волна / ид
        папка.mkdir(parents=True, exist_ok=True)
        # Серверные отказы, относящиеся к этому экрану — сразу в карточку.
        слова = ключи_экрана(э)
        сервер = []
        for ф, найдено in бэк.items():
            имя = str(ф).lower()
            if not any(с in имя for с in слова):
                continue
            for вид, н, кусок, _ in найдено:
                сервер.append(f"- `{вид}` · `{ф}:{н}`\n  ```\n{кусок}\n  ```")

        (папка / "KANDIDATY.md").write_text(
            f"# Кандидаты в блокировки · {ид}\n\n"
            f"Вычесано механически. Часть окажется техникой, а не блокировкой — это нормально,\n"
            f"скрипт сознательно тащит с запасом. Твоя работа — отделить доменные правила.\n\n"
            f"## Экран ({len(строки)})\n\n" + ("\n".join(строки) if строки else "_ничего не найдено_\n")
            + "\n\n## Сервер\n\nОтказы бэкенда собраны в `night/blockers/SERVER.md` — ищи там те,\n"
              "что относятся к твоему экрану, и сверяй с фронтовыми.\n",
            encoding="utf-8")
        (папка / "TYPE.txt").write_text("блокировки\n", encoding="utf-8")

    if not только_счёт:
        куски = []
        for ф, найдено in sorted(бэк.items()):
            строки = "\n".join(f"- `{в}` · `{ф}:{н}`\n  ```\n  {т}\n  ```" for в, н, т, _ in найдено)
            куски.append(f"### `{ф}`\n\n{строки}")
        (волна.parent / "SERVER.md").write_text(
            "# Отказы сервера\n\nОбщий список на все экраны: блокировка часто живёт в двух слоях,\n"
            "и расхождение между ними — самая дорогая находка.\n\n" + "\n\n".join(куски),
            encoding="utf-8")

    бэк_всего = sum(len(v) for v in бэк.values())
    print(f"\nэкранных кандидатов: {итого}")
    print(f"серверных отказов:   {бэк_всего}")
    if пусто:
        print(f"экранов без находок: {len(пусто)} ({', '.join(пусто)})")
    if not только_счёт:
        print(f"разложено по карточкам: {волна}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
