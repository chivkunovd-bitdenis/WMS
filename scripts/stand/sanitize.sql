-- Обезличивание боевого снимка перед тем, как отдать его стенду.
--
-- Главное правило: после этого файла в базе не должно остаться ни одного живого ключа
-- маркетплейса, кроме одного, названного владельцем. Ночью по стенду ходят восемь агентов;
-- уцелевший чужой токен означает настоящую поставку в WB от чужого имени.
--
-- Контакты селлеров НЕ трогаем — владелец решил оставить: агенту легче понять задачу,
-- когда он видит реальное название компании.
--
-- :живой_селлер подставляется скриптом.

\set ON_ERROR_STOP on

BEGIN;

-- 1. Ключи Wildberries: оставляем только у живого селлера, остальные удаляем целиком.
DELETE FROM seller_wildberries_credentials
WHERE seller_id <> :'живой_селлер';

-- 2. Ключи Честного знака и СУЗ: то же самое.
DELETE FROM seller_marking_credentials
WHERE seller_id <> :'живой_селлер';

-- 3. Пароли. Хэши боевых пользователей на ноутбуке не нужны, а войти на стенд надо.
--    Всем ставим «пароль не задан» — первый вход пойдёт через «Задать пароль».
--    Конкретному стендовому пользователю пароль проставит restore.sh хэшером самого
--    приложения, чтобы кликер мог залогиниться без ручных действий.
UPDATE users SET password_hash = '', must_set_password = true;

-- 4. Публикация остатков. На проде она выключена у всех складов и включать её обратно
--    нельзя без просьбы владельца. Снимок это состояние переносит как есть; здесь мы
--    только гарантируем, что стенд её не включит сам.
UPDATE fbs_warehouse_bindings SET stock_sync_enabled = false;
UPDATE products SET fbs_stock_sync_enabled = false;

COMMIT;

-- Итог для человека в логе.
SELECT 'ключей WB осталось: ' || count(*)::text FROM seller_wildberries_credentials;
SELECT 'ключей ЧЗ осталось: ' || count(*)::text FROM seller_marking_credentials;
SELECT 'селлеров в базе: '   || count(*)::text FROM sellers;
SELECT 'заказов FBS: '       || count(*)::text FROM fbs_orders;
SELECT 'поставок FBS: '      || count(*)::text FROM fbs_supplies;
