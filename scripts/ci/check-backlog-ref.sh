#!/usr/bin/env bash
# Гейт: в изменениях должен быть назван номер задачи из docs/BACKLOG.md.
#
# Ловит забывчивость, а не халтуру: проверить, что номер ПРАВИЛЬНЫЙ, код не может —
# автор подставит любой существующий. Смысл в том, чтобы связь «задача ↔ код» вообще
# существовала и её можно было проверить задним числом.
set -euo pipefail

BACKLOG="docs/BACKLOG.md"
BASE="${1:-origin/etalon}"

if [[ ! -f "$BACKLOG" ]]; then
  echo "ОШИБКА: нет $BACKLOG — единственного бэклога проекта." >&2
  exit 1
fi

# Номера задач ищем в сообщениях коммитов и в теле изменений.
range="${BASE}...HEAD"
refs="$(git log --format='%B' "$range" 2>/dev/null | grep -oE 'WMS-[0-9]{3}' | sort -u || true)"

if [[ -z "$refs" ]]; then
  cat >&2 <<'MSG'
ОШИБКА: ни в одном коммите не назван номер задачи.

Каждое изменение относится к задаче из docs/BACKLOG.md. Укажи её номер в
сообщении коммита, например:

    fix(фбс): подбор не раздаёт одну штуку двум заказам

    WMS-041

Если задачи для этой работы в бэклоге нет — заведи её там, дай следующий
свободный номер и только потом коммить. Заводить задачи в других файлах нельзя.
MSG
  exit 1
fi

missing=()
for ref in $refs; do
  grep -q "^## ${ref} " "$BACKLOG" || missing+=("$ref")
done

if (( ${#missing[@]} > 0 )); then
  echo "ОШИБКА: в $BACKLOG нет задач: ${missing[*]}" >&2
  echo "Заведи их там (заголовок вида '## WMS-NNN · название') и повтори." >&2
  exit 1
fi

echo "Гейт бэклога пройден: $(echo "$refs" | tr '\n' ' ')"
