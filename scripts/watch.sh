#!/usr/bin/env bash
# Фоновый присмотр за ночью. Будит дорогого сторожа только по симптому, не по таймеру.
#
# Разница принципиальная. Watchdog у Codex тикал каждые 15 минут десять часов подряд,
# сорок запусков — и не починил ничего, только жёг лимит. Здесь по таймеру работает
# бесплатная механическая проверка, а модель просыпается, только когда та нашла симптом.
#
#   ./scripts/watch.sh night/2026-08-22            присмотр с проверкой раз в 5 минут
#   ./scripts/watch.sh night/2026-08-22 --раз 600  своя частота
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WAVE="${1:?нужен путь к волне, например night/2026-08-22}"
EVERY=300
[[ "${2:-}" == "--раз" ]] && EVERY="${3:-300}"

# Чтобы сторож не будился по одному и тому же симптому каждые пять минут,
# пока чинится: между его запусками выдерживаем паузу.
COOLDOWN=$((20 * 60))
LAST=0

echo "присмотр за $WAVE: проверка каждые ${EVERY}с, сторож не чаще раза в $((COOLDOWN/60)) мин"

while true; do
  if ! pgrep -f "night.py ночь" >/dev/null 2>&1 && [[ -f "$ROOT/$WAVE/OTCHET.md" ]]; then
    echo "$(date +%H:%M) ночь закончена, отчёт на месте — выхожу"
    exit 0
  fi

  OUT="$(python3 "$ROOT/scripts/night_health.py" "$ROOT/$WAVE" 2>&1)" && CODE=0 || CODE=$?

  if [[ $CODE -eq 0 ]]; then
    echo "$(date +%H:%M) спокойно"
  else
    NOW=$(date +%s)
    if (( NOW - LAST < COOLDOWN )); then
      echo "$(date +%H:%M) симптом есть, но сторож будился недавно — жду"
    else
      echo "$(date +%H:%M) СИМПТОМ — бужу сторожа"
      echo "$OUT" | sed 's/^/    /'
      LAST=$NOW
      claude -p "Ночная волна: \`$ROOT/$WAVE\`. Рабочая копия: \`$ROOT\`, все пути абсолютные.

Механическая проверка нашла симптом:

$OUT

Развяжи тупик строго в рамках своей роли и выключись. Работу за агентов не делай." \
        --agent watchdog --permission-mode acceptEdits 2>&1 | tail -4 | sed 's/^/    /'
    fi
  fi
  sleep "$EVERY"
done
